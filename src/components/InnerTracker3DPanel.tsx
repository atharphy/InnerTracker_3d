const VISIBILITY_KEY = 'cmsit-inner-tracker-3d:visibility';

function loadVisibility(remember: boolean): VisibilityState {
  if (!remember) {
    return defaultVisibility();
  }
  try {
    const saved = window.localStorage.getItem(VISIBILITY_KEY);
    if (!saved) {
      return defaultVisibility();
    }
    const parsed = JSON.parse(saved) as VisibilityState;
    if (
      parsed.TBPX?.length === 4
      && parsed.TFPX?.length === 8
      && parsed.TEPX?.length === 4
      && parsed.TBPXParts?.length === 4
      && parsed.TFPXParts?.length === 4
      && parsed.TEPXParts?.length === 4
    ) {
      return parsed;
    }
  } catch {
    // Fall back to all-visible state if storage is unavailable or invalid.
  }
  return defaultVisibility();
}

function detailUrl(
  uid: string,
  module: ModuleDescriptor,
  measurement: ModuleMeasurement,
  chipIndex?: number
): string {
  const params = new URLSearchParams();
  params.set('var-module', measurement.moduleId);
  params.set('var-efuse', chipIndex === undefined ? 'All' : measurement.chips[chipIndex]?.efuse ?? 'All');
  params.set('var-chip', chipIndex === undefined ? 'All' : String(chipIndex));
  params.set('var-subdetector', module.subdetector);
  if (module.layer !== undefined) {
    params.set('var-layer', String(module.layer));
    params.set('var-ladder', String(module.ladder));
    params.set('var-z_side', String(module.zSide));
  } else {
    params.set('var-detector_side', String(module.side));
    params.set('var-disk', String(module.disk));
    params.set('var-ring', String(module.ring));
    params.set('var-half', String(module.half));
  }
  params.set('var-module_index', String(module.moduleIndex));
  params.set('var-return_url', window.location.href);
  params.set('from', 'now-15m');
  params.set('to', 'now');
  return `/d/${encodeURIComponent(uid)}/${encodeURIComponent(uid)}?${params.toString()}`;
}

export const InnerTracker3DPanel = ({
  data,
  options,
  replaceVariables,
}: PanelProps<InnerTracker3DOptions>) => {
  const effectiveOptions = useMemo(
    () => {
      const merged = { ...DEFAULT_OPTIONS, ...options };
      // Migrate dashboards generated by the initial release, whose no-data
      // colour was nearly indistinguishable from Grafana's dark background.
      if (
        !merged.noDataColor
        || ['#252a32', '#68758a', '#111820'].includes(merged.noDataColor.toLowerCase())
      ) {
        merged.noDataColor = DEFAULT_OPTIONS.noDataColor;
      }
      const register = replaceVariables('${register}');
      const automaticLimits = REGISTER_LIMITS[register];
      merged.lowerLimit = effectiveRegisterLimit(
        replaceVariables('${low_limit}'),
        automaticLimits?.lower
      );
      merged.upperLimit = effectiveRegisterLimit(
        replaceVariables('${high_limit}'),
        automaticLimits?.upper
      );
      return merged;
    },
    [options, replaceVariables]
  );
  const hostRef = useRef<HTMLDivElement>(null);
  const sceneRef = useRef<DetectorScene>();
  const [hovered, setHovered] = useState<HoveredModule>();
  const [cameraMode, setCameraMode] = useState<CameraMode>('rotate');
  const [inventoryOpen,setInventoryOpen]=useState(false);
  const [hardwareDetails,setHardwareDetails]=useState({tbpxPortcards:true,tepxPortcards:true,cartridges:effectiveOptions.defaultAssembly==='full',rails:effectiveOptions.defaultAssembly==='full',mechanics:true,installedOnly:false,connectedPortcardsOnly:false,electrical:effectiveOptions.defaultAssembly==='full',tbpxCables:effectiveOptions.defaultAssembly==='full',exterior:effectiveOptions.defaultAssembly==='full',cylinderLeft:true,axisX:true,axisY:true,axisZ:effectiveOptions.showBeamAxis});
  const [beamPipeVisible, setBeamPipeVisible] = useState(effectiveOptions.defaultAssembly==='full');
  const [serviceCylinderVisible, setServiceCylinderVisible] = useState(effectiveOptions.defaultAssembly==='full');
  const [serviceCylinderCutaway, setServiceCylinderCutaway] = useState(effectiveOptions.serviceCylinderCutaway);
  const [moduleAppearance, setModuleAppearance] = useState<ModuleAppearance>(effectiveOptions.moduleAppearance);
  const [portcardsVisible, setPortcardsVisible] = useState(effectiveOptions.defaultAssembly==='full');
  const [antlersVisible, setAntlersVisible] = useState(effectiveOptions.defaultAssembly==='full');
  const [servicesVisible, setServicesVisible] = useState(effectiveOptions.defaultAssembly==='full');
  useEffect(() => { setModuleAppearance(effectiveOptions.moduleAppearance); }, [effectiveOptions.moduleAppearance]);




  useEffect(() => {
    const register = replaceVariables('${register}');
    const defaults = REGISTER_LIMITS[register];
    const rawLow = replaceVariables('${low_limit}');
    const rawHigh = replaceVariables('${high_limit}');
    const updates: Record<string, string> = {};
    if (rawLow.trim().toLowerCase() === 'auto') {
      updates['var-low_limit'] = defaults?.lower === undefined
        ? 'None'
        : String(defaults.lower);
    }
    if (rawHigh.trim().toLowerCase() === 'auto') {
      updates['var-high_limit'] = defaults?.upper === undefined
        ? 'None'
        : String(defaults.upper);
    }
    if (Object.keys(updates).length > 0) {
      locationService.partial(updates, true);
    }
  }, [replaceVariables]);
  const [visibility, setVisibility] = useState<VisibilityState>(() =>
    loadVisibility(effectiveOptions.rememberVisibility)
  );

  const modules = useMemo(
    () => buildDetectorGeometry(geometryFromJson(effectiveOptions.geometryOverridesJson)),
    [effectiveOptions.geometryOverridesJson]
  );
  const measurements = useMemo(
    () => mapMeasurementsToModules(
      data,
      modules,
      effectiveOptions.hardwareMappingJson,
      effectiveOptions.aggregation
    ),
    [data, modules, effectiveOptions.hardwareMappingJson, effectiveOptions.aggregation]
  );
  const detailsUidRef = useRef(effectiveOptions.detailsDashboardUid);

  useEffect(() => {
    detailsUidRef.current = effectiveOptions.detailsDashboardUid;
  }, [effectiveOptions.detailsDashboardUid]);

  const selectModule = useCallback((
    module: ModuleDescriptor,
    chipIndex: number,
    measurement?: ModuleMeasurement
  ) => {
    if (!measurement?.moduleId || !detailsUidRef.current.trim()) {
      return;
    }
    window.location.href = detailUrl(
      detailsUidRef.current,
      module,
      measurement,
      chipIndex
    );
  }, []);

  const inventory=useMemo(()=>buildInventory(effectiveOptions.hardwareMappingJson,modules,measurements),[effectiveOptions.hardwareMappingJson,modules,measurements]);
  const installedIds=useMemo(()=>new Set(buildInventory(effectiveOptions.hardwareMappingJson,modules,new Map()).entries.filter(e=>e.installed).map(e=>e.module.id)),[effectiveOptions.hardwareMappingJson,modules]);
  const focusInventoryModule=(module:ModuleDescriptor)=>{
    const index=(module.layer??module.disk??1)-1;
    const parts=elementParts(visibility,module.subdetector,index);parts[sectionKeys(module.subdetector).indexOf(module.sectionKey)]=true;
    let next=setElementParts(visibility,module.subdetector,index,parts);
    const dee=moduleDee(module);
    if(dee!==undefined){next=setDee(next,module.subdetector,index,sectionKeys(module.subdetector).indexOf(module.sectionKey),dee,true);}
    setVisibility(next);sceneRef.current?.focusModule(module);
  };

  const portcardInventory=useMemo(()=>buildPortcardInventory(effectiveOptions.portcardMappingJson,effectiveOptions.hardwareMappingJson,modules),[effectiveOptions.portcardMappingJson,effectiveOptions.hardwareMappingJson,modules]);
  const applyAssembly=(full:boolean)=>{
    setBeamPipeVisible(full);setServiceCylinderVisible(full);setServiceCylinderCutaway(false);
    setServicesVisible(full);setPortcardsVisible(full);setAntlersVisible(full);
    setHardwareDetails(previous=>({...previous,installedOnly:false,connectedPortcardsOnly:false,mechanics:true,tbpxPortcards:true,tepxPortcards:true,cartridges:full,rails:full,tbpxCables:full,electrical:full,exterior:full,cylinderLeft:true}));
    setVisibility(defaultVisibility());
  };
  useEffect(()=>{applyAssembly(effectiveOptions.defaultAssembly==='full');},[effectiveOptions.defaultAssembly]);
  const focusInstalledModules=()=>{
    setHardwareDetails({...hardwareDetails,installedOnly:true,mechanics:false,tbpxCables:false,electrical:false});
    setModuleAppearance('photos');setServiceCylinderVisible(false);setServicesVisible(false);setPortcardsVisible(false);setAntlersVisible(false);setBeamPipeVisible(false);
    let next=visibility;
    inventory.entries.filter(e=>e.installed).forEach(({module})=>{const index=(module.layer??module.disk??1)-1;const parts=elementParts(next,module.subdetector,index);parts[sectionKeys(module.subdetector).indexOf(module.sectionKey)]=true;next=setElementParts(next,module.subdetector,index,parts);});
    setVisibility(next);sceneRef.current?.focusInstalledModules();
  };

  useEffect(() => {
    if (!hostRef.current) {
      return;
    }
    const scene = new DetectorScene(hostRef.current, modules, effectiveOptions, {
      onHover: setHovered,
      onSelect: selectModule,
    });
    sceneRef.current = scene;
    scene.setInstalledModules(installedIds);
    scene.setComponentVisibility(hardwareDetails);
    scene.setVisibility(visibility);
    scene.setCameraMode(cameraMode);
    scene.setBeamPipeVisible(beamPipeVisible);
    scene.setServiceCylinderVisible(serviceCylinderVisible);
    scene.setServiceCylinderCutaway(serviceCylinderCutaway);
    scene.setServicesVisible(servicesVisible);
    scene.updateOptions({ ...effectiveOptions, moduleAppearance, showPortcards: portcardsVisible, showAntlers: antlersVisible, showServiceCylinder: serviceCylinderVisible, serviceCylinderCutaway, showServices: servicesVisible });
    scene.updateMeasurements(measurements);
    return () => {
      scene.dispose();
      sceneRef.current = undefined;
    };
    // Scene recreation is limited to topology or navigation changes.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [modules, selectModule]);

  useEffect(() => {
    sceneRef.current?.updateOptions({ ...effectiveOptions, showServiceCylinder: serviceCylinderVisible, serviceCylinderCutaway, showServices: servicesVisible, moduleAppearance, showPortcards: portcardsVisible, showAntlers: antlersVisible });
  }, [effectiveOptions, serviceCylinderVisible, serviceCylinderCutaway, servicesVisible, moduleAppearance, portcardsVisible, antlersVisible]);

  useEffect(()=>{sceneRef.current?.setInstalledModules(installedIds);},[installedIds]);
  useEffect(()=>{sceneRef.current?.setComponentVisibility(hardwareDetails);},[hardwareDetails]);

  useEffect(() => {
    sceneRef.current?.updateMeasurements(measurements);
  }, [measurements]);

  useEffect(() => {
    sceneRef.current?.setVisibility(visibility);
    if (effectiveOptions.rememberVisibility) {
      try {
        window.localStorage.setItem(VISIBILITY_KEY, JSON.stringify(visibility));
      } catch {
        // The panel remains usable when local storage is blocked.
      }
    }
  }, [visibility, effectiveOptions.rememberVisibility]);

  useEffect(() => {
    sceneRef.current?.setCameraMode(cameraMode);
  }, [cameraMode]);

  useEffect(() => {
    sceneRef.current?.setBeamPipeVisible(beamPipeVisible);
  }, [beamPipeVisible]);

  useEffect(() => {
    sceneRef.current?.setServiceCylinderVisible(serviceCylinderVisible);
  }, [serviceCylinderVisible]);

  useEffect(() => {
    sceneRef.current?.setServiceCylinderCutaway(serviceCylinderCutaway);
  }, [serviceCylinderCutaway]);

  useEffect(() => {
    sceneRef.current?.setServicesVisible(servicesVisible);
  }, [servicesVisible]);

  const visibleElements =
    visibility.TBPX.filter(Boolean).length
    + visibility.TFPX.filter(Boolean).length
    + visibility.TEPX.filter(Boolean).length;
  const visibleSections = visiblePartCount(visibility);
  const lowLabel = effectiveOptions.lowerLimit === undefined
    ? 'None'
    : String(effectiveOptions.lowerLimit);
  const highLabel = effectiveOptions.upperLimit === undefined
    ? 'None'
    : String(effectiveOptions.upperLimit);

  return (
    <div className="cmsit3d-root">
      <VisibilityTree
        hardwareDetails={hardwareDetails} onHardwareDetailsChange={setHardwareDetails}
        moduleAppearance={moduleAppearance} onModuleAppearanceChange={setModuleAppearance}
        portcardsVisible={portcardsVisible} onPortcardsVisibleChange={setPortcardsVisible}
        antlersVisible={antlersVisible} onAntlersVisibleChange={setAntlersVisible}
        value={visibility}
        onChange={setVisibility}
        onResetCamera={() => sceneRef.current?.resetCamera()}
        cameraMode={cameraMode}
        onCameraModeChange={setCameraMode}
        beamPipeVisible={beamPipeVisible}
        onBeamPipeVisibleChange={setBeamPipeVisible}
        serviceCylinderVisible={serviceCylinderVisible}
        onServiceCylinderVisibleChange={setServiceCylinderVisible}
        serviceCylinderCutaway={serviceCylinderCutaway}
        onServiceCylinderCutawayChange={setServiceCylinderCutaway}
        servicesVisible={servicesVisible}
        onServicesVisibleChange={setServicesVisible}
      />
      <main className="cmsit3d-viewport">
        <div ref={hostRef} className="cmsit3d-canvas" />
        <div className="cmsit3d-status">
          <span>{visibleElements}/16 elements, {visibleSections}/64 parts visible</span>
          <span>{measurements.size}/{modules.length} modules with data</span>
          {hardwareDetails.connectedPortcardsOnly && <span>Connected portcards only ({portcardInventory.entries.filter(c=>c.connections.length>0).length})</span>}
          {hardwareDetails.installedOnly && <span>Installed modules only ({installedIds.size})</span>}
        </div>
        <div className="cmsit3d-physical-views" aria-label="Detector camera views">
          <button onClick={()=>applyAssembly(false)}>Subsystems only</button>
          <button onClick={()=>applyAssembly(true)}>Full assembly</button>
          <button onClick={() => sceneRef.current?.resetCamera()}>Reset camera</button>
          <button onClick={()=>{setServiceCylinderVisible(true);setServiceCylinderCutaway(false);setServicesVisible(true);setHardwareDetails({...hardwareDetails,exterior:true,cylinderLeft:true});sceneRef.current?.resetCamera();}}>Exterior / services</button>
          <button onClick={focusInstalledModules}>Installed close-up</button>
          <button aria-expanded={inventoryOpen} onClick={()=>setInventoryOpen(!inventoryOpen)}>Module inventory ({inventory.entries.length})</button>
          {(['TBPX', 'TFPX', 'TEPX'] as const).map(region => (
            <button key={region} onClick={() => sceneRef.current?.focusRegion(region)}>{region} close-up</button>
          ))}
          <span>Physical scale · 5.3 m active span · service routing illustrative</span>
        </div>
        <div className="cmsit3d-legend">
          <span>Limits: {lowLabel} – {highLabel}</span>
          <span><i style={{ background: effectiveOptions.goodColor }} />Within limits</span>
          <span><i style={{ background: effectiveOptions.badColor }} />Outside limits</span>
          <span><i style={{ background: effectiveOptions.noDataColor }} />No data</span>
        </div>
      </main>
      {inventoryOpen && <InventoryPane entries={inventory.entries} issues={[...inventory.issues,...portcardInventory.issues]} portcards={portcardInventory.entries} onClose={()=>setInventoryOpen(false)} onFocus={focusInventoryModule}/>}
      <Tooltip hovered={hovered} />
    </div>
  );
};
